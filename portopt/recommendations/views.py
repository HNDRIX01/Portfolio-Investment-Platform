@api_view(["POST"])
@permission_classes([IsAuthenticated])
def save_generated_portfolio(request):
    """
    Receives (via POST) JSON like:
      {
        "portfolio_choice": 3,
        "portfolio_name": "My Third Portfolio"
      }
    Creates a Portfolio + PortfolioAssets for the authenticated user.
    Returns:
      {
        "portfolio_id": "<UUID>",
        "portfolio_name": "My Third Portfolio"
      }
    """

    user = request.user
    if not user.is_authenticated:
        return Response(
            {"error": "User is not authenticated."},
            status=status.HTTP_403_FORBIDDEN
        )

    # 1) Parse input data
    data = request.data
    portfolio_choice = data.get("portfolio_choice")  # an integer 1..3
    portfolio_name = data.get("portfolio_name")      # a string

    if not portfolio_choice or not isinstance(portfolio_choice, int):
        return Response(
            {"error": "Invalid or missing 'portfolio_choice' (must be an integer)."},
            status=status.HTTP_400_BAD_REQUEST
        )

    if not portfolio_name or not isinstance(portfolio_name, str):
        return Response(
            {"error": "Invalid or missing 'portfolio_name' (must be a string)."},
            status=status.HTTP_400_BAD_REQUEST
        )

    # 2) Path to the JSON file generated by your run_portfolio_analysis
    json_file_path = os.path.join(settings.MEDIA_ROOT, "portfolios.json")
    if not os.path.exists(json_file_path):
        return Response(
            {"error": f"JSON file not found at {json_file_path}."},
            status=status.HTTP_500_INTERNAL_SERVER_ERROR
        )

    try:
        # 3) Create the Portfolio + PortfolioAssets via your helper
        new_portfolio = create_portfolio_from_json(
            json_file_path=json_file_path,
            portfolio_choice=portfolio_choice,
            portfolio_name=portfolio_name,
            user=user
        )

        # 4) Return success
        return Response({
            "portfolio_id": str(new_portfolio.id),
            "portfolio_name": new_portfolio.name
        }, status=status.HTTP_201_CREATED)

    except ValueError as ve:
        # e.g., if portfolio_choice isn't found in the JSON
        return Response({"error": str(ve)}, status=status.HTTP_400_BAD_REQUEST)
    except Exception as e:
        return Response({"error": str(e)}, status=status.HTTP_500_INTERNAL_SERVER_ERROR)





